#!/bin/sh

# Keep schema-owned notices prominent where generators omit or bury them.
# Run from the repository root after protobuf generation.
set -eu

find ./api ./x -type f \( -name '*.pulsar.go' -o -name '*.pb.gw.go' \) -print |
while IFS= read -r generated; do
  source=$(sed -n 's|^// source: |proto/|p' "$generated" | head -n 1)
  case "$source" in
    proto/ark/*.proto) ;;
    *) echo "Missing or invalid source metadata: $generated" >&2; exit 1 ;;
  esac
  case "$source" in
    */../*|*/./*) echo "Invalid source path: $generated" >&2; exit 1 ;;
  esac
  if [ ! -f "$source" ]; then
    echo "Missing source $source for $generated" >&2
    exit 1
  fi

  # A notice is four consecutive comments immediately before the package.
  # Schemas without a notice leave their generated output unchanged.
  notice=$(awk '
    /^\/\/ SPDX-License-Identifier:/ { active = 1 }
    active && /^package / { if (count != 4) exit 1; done = 1; exit }
    active { if ($0 !~ /^\/\/ /) exit 1; print; count++ }
    END { if (active && !done) exit 1 }
  ' "$source") || { echo "Malformed attribution notice: $source" >&2; exit 1; }
  [ -n "$notice" ] || continue

  if [ "$(sed -n '2,5p' "$generated")" = "$notice" ]; then
    continue
  fi
  case "$(head -n 1 "$generated")" in
    '// Code generated by '*'. DO NOT EDIT.') ;;
    *) echo "Missing generated-file marker: $generated" >&2; exit 1 ;;
  esac

  notice_tmp=$(mktemp "${generated}.notice.XXXXXX")
  trap 'rm -f "$notice_tmp"' EXIT HUP INT TERM
  {
    head -n 1 "$generated"
    printf '%s\n\n' "$notice"
    tail -n +2 "$generated"
  } > "$notice_tmp"
  # Keep the output file mode; retain any copy emitted farther down by Pulsar.
  cat "$notice_tmp" > "$generated"
  rm -f "$notice_tmp"
  trap - EXIT HUP INT TERM
done
